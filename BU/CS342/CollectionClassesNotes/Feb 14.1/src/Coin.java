
public class Coin {
	private int year;
	private char mint;
	private String condition;
	
	public int getYear() {
		return year;
	}
	public void setYear(int year) {
		this.year = year;
	}
	public char getMint() {
		return mint;
	}
	public void setMint(char mint) {
		this.mint = mint;
	}
	public String getCondition() {
		return condition;
	}
	public void setCondition(String condition) {
		this.condition = condition;
	}
}
