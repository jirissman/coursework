package SinglyLinkedList;

public class Node {
	private Integer data;
	private Node next;
	/**
	 * @return the data
	 */
	public Integer getData() {
		return data;
	}
	/**
	 * @param data the data to set
	 */
	public void setData(Integer data) {
		this.data = data;
	}
	/**
	 * @return the next
	 */
	public Node getNext() {
		return next;
	}
	/**
	 * @param next the next to set
	 */
	public void setNext(Node next) {
		this.next = next;
	}
}
