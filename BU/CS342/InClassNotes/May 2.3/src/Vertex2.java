
public class Vertex2 {

	private String label;
	private Edge list;
	private Vertex2 next;
	private int vertex;
	
	public String getLabel() {
		return label;
	}
	public void setLabel(String label) {
		this.label = label;
	}
	public Edge getList() {
		return list;
	}
	public void setList(Edge list) {
		this.list = list;
	}
	public Vertex2 getNext() {
		return next;
	}
	public void setNext(Vertex2 next) {
		this.next = next;
	}
	public int getVertex() {
		return vertex;
	}
	public void setVertex(int vertex) {
		this.vertex = vertex;
	}
}
